# --------------------------------------------------------------------------
# End-to-end run (what app.py calls)
# --------------------------------------------------------------------------


async def run_upload(video_path: str | Path, browser: str = "brave") -> None:
    """*Usage:*
    >>> asyncio.run(run_upload("videos/my_video.mp4"))
    """
    if not cdp_is_up():
        await asyncio.to_thread(lambda: start_browser(browser).close())

    async with async_update_state("yt_upload", total=3) as progress:
        async with async_browser_session() as session:
            await progress(current=1, message="Opening YouTube Studio...")
            await open_studio(session.page)

            await progress(current=2, message="Uploading video...")
            await upload_video(session.page, video_path, progress=progress)

            await progress(current=3, message="Upload started.")


if __name__ == "__main__":
    import sys

    if len(sys.argv) != 2:
        print("Usage: python yt.py <path-to-video>")
        raise SystemExit(1)
    asyncio.run(run_upload(sys.argv[1]))