YT_HOME_URL = "https://www.youtube.com/"
YT_STUDIO_URL = "https://studio.youtube.com/"


# --------------------------------------------------------------------------
# Studio navigation
# --------------------------------------------------------------------------
# The browser is already logged in and cookies are shared across every
# session that attaches to the CDP profile (see start_browser() /
# async_browser_session() in utils.py) - so the click-through-the-menu
# path (avatar -> "YouTube Studio") isn't actually required to reach
# Studio. open_studio() below just navigates straight there. Keeping
# click_to_studio() around as a fallback for verifying the manual UI
# path still works, or for a cold profile where cookies haven't landed.


async def open_studio(page: AsyncPage) -> None:
    """*Usage:*
    >>> async with async_browser_session() as session:
    ...     await open_studio(session.page)
    """
    await page.goto(YT_STUDIO_URL, wait_until="domcontentloaded")


async def click_to_studio(page: AsyncPage) -> None:
    """
    Fallback path that mimics the manual click-through.

    NOTE: the dropdown's link to Studio uses id="endpoint", but every
    ytd-compact-link-renderer on the page reuses that same id - it is
    not unique. Clicking "#endpoint" directly raises Playwright's
    strict-mode error ("multiple elements match"). Filter by the
    link's visible text instead, as done below.

    *Usage:*
    >>> async with async_browser_session() as session:
    ...     await click_to_studio(session.page)
    """
    await page.goto(YT_HOME_URL, wait_until="domcontentloaded")
    await page.click("#avatar-btn")
    await page.get_by_text("YouTube Studio", exact=True).click()
    await page.wait_for_url(f"{YT_STUDIO_URL}*")


