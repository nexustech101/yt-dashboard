async def goto_studio_section(page: AsyncPage, label: str) -> None:
    """*Usage:*
    >>> async with async_browser_session() as session:
    ...     await open_studio(session.page)
    ...     await goto_studio_section(session.page, "Content")
    """
    if label == "Settings":
        await page.click("#settings-item")
        return
    await page.locator("tp-yt-paper-item", has_text=label).first.click()


# --------------------------------------------------------------------------
# Upload
# --------------------------------------------------------------------------
# CAUTION: the "Upload videos" button on the dashboard's empty-state
# card (the one under "Want to see metrics on your recent video?")
# only exists before the channel has any videos - it disappears for
# good after the first upload. Don't build around it. The persistent
# entry point is the "Create" control in Studio's top bar (#upload-icon
# per your notes), which is there regardless of upload history.


async def upload_video(
    page: AsyncPage,
    video_path: str | Path,
    progress=None,
) -> None:
    """
    Opens the native file picker via Studio's persistent upload
    control and hands it the video file. Stops once the details wizard
    opens - filling in title/description/visibility/publish is a TODO
    once you've mapped those selectors (they're dynamic per step, so
    grab them from the DOM the same way you did for the ones above).

    expect_file_chooser() intercepts the browser's file-chooser event
    directly, so there's no need for the goog_-prefixed "Select files"
    id from your notes - that id is autogenerated by Closure per page
    load and won't exist under that name on the next run anyway.

    *Usage:*
    >>> async with async_browser_session() as session:
    ...     await open_studio(session.page)
    ...     await upload_video(session.page, "videos/my_video.mp4")
    """
    video_path = Path(video_path)
    if not video_path.exists():
        raise FileNotFoundError(video_path)

    if progress:
        await progress(message="Opening upload dialog...")

    async with page.expect_file_chooser() as fc_info:
        await page.click("#upload-icon")
        # If #upload-icon opens a "Create" dropdown rather than the
        # file picker directly, uncomment the line below - you already
        # have the locator for it in your notes:
        # await page.get_by_label("Upload videos").click()
    file_chooser = await fc_info.value
    await file_chooser.set_files(str(video_path))

    if progress:
        await progress(message="File selected, waiting for upload to start...")

